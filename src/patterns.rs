pub struct Pattern {
    name: &'static str,
    width: u32,
    height: u32,
    pixels: &'static [u8],
}

macro_rules! rgba_pattern {
    ($($cell:expr),* $(,)?) => {
        &[
            $(
                if $cell != 0 { 255 } else { 0 },
                if $cell != 0 { 255 } else { 0 },
                if $cell != 0 { 255 } else { 0 },
                255,
            )*
        ]
    };
}

